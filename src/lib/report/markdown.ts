import type { Critique } from "@/lib/critique/schema";
import type { Pair } from "@/lib/palette";

export type ReportInput = {
  fileName: string;
  date: Date;
  pairs: Pair[];
  critique: Critique | null;
};

const VERDICT_WORDS: Record<Pair["verdict"], string> = {
  fail: "Fails AA",
  "large-only": "Large text only",
  pass: "Passes AA",
};

const wcagLink = (sc: string) =>
  `[WCAG ${sc}](https://www.w3.org/WAI/WCAG22/quickref/#:~:text=${encodeURIComponent(sc)})`;

/** A shareable Markdown report: paste it into a ticket, a PR or a design review doc. */
export function buildMarkdownReport({ fileName, date, pairs, critique }: ReportInput): string {
  const lines = [
    `# Design review: ${fileName}`,
    "",
    `Generated by AI Design Assistant on ${date.toISOString().slice(0, 10)}.`,
    "",
  ];

  if (critique) {
    lines.push("## Summary", "", critique.summary, "");
    if (critique.strengths.length > 0) {
      lines.push("### What works", "", ...critique.strengths.map((s) => `- ${s}`), "");
    }
    lines.push(`## Issues (${critique.issues.length})`, "");
    critique.issues.forEach((issue, i) => {
      const tags = [issue.severity, issue.category, issue.wcag ? wcagLink(issue.wcag) : null].filter(Boolean);
      lines.push(
        `### ${i + 1}. ${issue.title}`,
        "",
        `${tags.join(" · ")} · ${issue.location}`,
        "",
        `**Problem:** ${issue.problem}`,
        "",
        `**Fix:** ${issue.fix}`,
        "",
      );
    });
  }

  lines.push("## Measured colour contrast", "");
  if (pairs.length === 0) {
    lines.push("No colour pairs were measured.", "");
  } else {
    lines.push("| Foreground | Background | Ratio | Result |", "| --- | --- | --- | --- |");
    for (const p of pairs) {
      lines.push(`| \`${p.fg.hex}\` | \`${p.bg.hex}\` | ${p.ratio.toFixed(2)}:1 | ${VERDICT_WORDS[p.verdict]} |`);
    }
    lines.push(
      "",
      "Contrast is measured from the screenshot's pixels against WCAG 2.2 AA (4.5:1 body text, 3:1 large text).",
      "",
    );
  }

  if (critique) {
    lines.push("_The issues above were written by AI. Check them against the design before acting on them._", "");
  }
  return lines.join("\n");
}
